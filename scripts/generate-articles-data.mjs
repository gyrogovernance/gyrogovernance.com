#!/usr/bin/env node

/**
 * Generate articles-data.ts from markdown files at build time
 * This ensures the client-side data is always in sync with the content
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import matter from 'gray-matter';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const CONTENT_DIR = path.join(__dirname, '..', 'src', 'content', 'articles');
const OUTPUT_FILE = path.join(__dirname, '..', 'src', 'lib', 'articles-data.ts');

function parseArticleFile(filePath) {
  try {
    const file = fs.readFileSync(filePath, 'utf8');
    const { data } = matter(file);
    const slug = path.basename(filePath).replace(/\.md$/i, '');
    
    if (!data.title || !data.category || !data.date) {
      console.warn(`⚠️  Skipping ${slug}: missing required fields (title, category, or date)`);
      return null;
    }
    
    return {
      slug,
      title: String(data.title),
      excerpt: String(data.excerpt || ''),
      category: String(data.category),
      date: String(data.date),
      coverImage: data.coverImage ? String(data.coverImage) : undefined,
      tags: Array.isArray(data.tags) ? data.tags.map(String) : undefined,
      featured: typeof data.featured === 'boolean' ? data.featured : undefined,
    };
  } catch (error) {
    console.error(`Error parsing ${filePath}:`, error);
    return null;
  }
}

function generateArticlesData() {
  console.log('🔄 Generating articles data...');
  
  // Ensure content directory exists
  if (!fs.existsSync(CONTENT_DIR)) {
    console.error(`❌ Content directory not found: ${CONTENT_DIR}`);
    process.exit(1);
  }
  
  // Read all markdown files
  const files = fs.readdirSync(CONTENT_DIR).filter(f => f.toLowerCase().endsWith('.md'));
  console.log(`📄 Found ${files.length} markdown file(s)`);
  
  // Parse articles
  const articles = files
    .map(f => parseArticleFile(path.join(CONTENT_DIR, f)))
    .filter(Boolean)
    .sort((a, b) => (a.date < b.date ? 1 : -1)); // Sort by date descending
  
  console.log(`✅ Parsed ${articles.length} valid article(s)`);
  
  // Extract unique categories
  const uniqueCategories = [...new Set(articles.map(a => a.category))].sort();
  const categoryType = uniqueCategories.map(c => `'${c}'`).join(' | ');
  
  // Generate TypeScript file content
  const tsContent = `// Auto-generated at build time from markdown files
// DO NOT EDIT THIS FILE MANUALLY - it will be overwritten
// To update articles, edit the markdown files in src/content/articles/

export type ArticleCategory = ${categoryType};

export interface ArticleMeta {
  slug: string;
  title: string;
  excerpt: string;
  category: ArticleCategory;
  date: string; // ISO string
  coverImage?: string;
  tags?: string[];
  featured?: boolean;
}

export const articlesData: ArticleMeta[] = ${JSON.stringify(articles, null, 2)};

export function getArticlesData(): ArticleMeta[] {
  return articlesData;
}

export function getFeaturedArticlesData(): ArticleMeta[] {
  return articlesData.filter(article => article.featured === true);
}

export function getAllTagsData(): string[] {
  const tags = new Set<string>();
  articlesData.forEach(article => {
    if (article.tags) {
      article.tags.forEach(tag => tags.add(tag));
    }
  });
  return Array.from(tags).sort((a, b) => a.localeCompare(b));
}
`;
  
  // Write the file
  fs.writeFileSync(OUTPUT_FILE, tsContent, 'utf8');
  console.log(`✨ Generated: ${OUTPUT_FILE}`);
  console.log('✅ Articles data generation complete!');
}

// Run the generator
generateArticlesData();

